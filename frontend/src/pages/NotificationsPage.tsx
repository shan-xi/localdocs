import { useAppContext } from '../app-context'
import { EmptyState } from '../components/common/EmptyState'

export function NotificationsPage() {
  const { notice, error, dismissMessages, openPage } = useAppContext()
  return <div className="app-page">
    <div className="page-heading"><p className="eyebrow">UPDATES</p><h1>Notifications</h1><p>Messages generated by actions in this browser session.</p></div>
    {notice || error ? <div className="page-card notification-card"><span className={`notice-mark ${error ? 'notice-error' : ''}`}>{error ? '!' : '✓'}</span>
      <div><strong>{error ? 'Latest error' : 'Latest notification'}</strong><p>{error || notice}</p></div>
      <button className="secondary-button" type="button" onClick={dismissMessages}>Dismiss</button>
    </div> : <EmptyState title="You're all caught up" description="There are no current success or error messages. Upload, delete, or refresh documents to generate an update." action="Go to Documents" onAction={() => openPage('documents')} />}
  </div>
}
